# Extract DEFAULT_FOODS from the legacy (untrusted) NutriPro file into a JS module. Read-only, no eval.
import re, sys, json
src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding='utf-8').read()
start = text.index('const DEFAULT_FOODS = {')
end = text.index('\n};', start)
block = text[start:end]
row = re.compile(r'^\s*([A-Za-z0-9_]+)\s*:\s*\{(.*)\}\s*,?\s*$')
field = re.compile(r'(\w+)\s*:\s*("(?:[^"\\]|\\.)*"|-?\d+(?:\.\d+)?)')
foods, bad = [], 0
def clean(s, n):
    s = re.sub(r'[<>`\\\x00-\x1f]', '', s).strip()
    return s[:n]
for line in block.split('\n')[1:]:
    m = row.match(line)
    if not m: 
        if line.strip(): bad += 1
        continue
    fid, body = m.group(1), m.group(2)
    d = {}
    for k, v in field.findall(body):
        d[k] = json.loads(v) if v.startswith('"') else float(v)
    try:
        name = clean(d['name'], 80)
        vals = [float(d[k]) for k in ('cal', 'pro', 'carb', 'fat', 'per')]
    except (KeyError, ValueError, TypeError):
        bad += 1; continue
    if not name or any(not (0 <= v <= 5000) for v in vals) or vals[4] <= 0:
        bad += 1; continue
    kcal, p, c, f, per = vals
    aliases = []
    base = re.sub(r'\s*\([^)]*\)\s*', ' ', name).strip()
    if base and base != name: aliases.append(base)
    paren = re.findall(r'\(([^)]*)\)', name)
    for x in paren:
        x = x.strip()
        if re.search(r'[A-Za-z]{3,}', x) and not re.search(r'\d', x): aliases.append(x)
    g = lambda x: int(x) if x == int(x) else round(x, 1)
    foods.append({'id': 'd:' + clean(fid, 30), 'name': name, 'aliases': aliases, 'per': g(per),
                  'unit': clean(str(d.get('unit', 'جرام')), 20) or 'جرام', 'cat': clean(str(d.get('cat', '')), 30),
                  'kcal': g(kcal), 'p': g(p), 'c': g(c), 'f': g(f)})
ids = [x['id'] for x in foods]
assert len(ids) == len(set(ids)), 'duplicate ids'
with open(out, 'w', encoding='utf-8') as fh:
    fh.write('// Generated by scripts/extract_foods.py from the legacy NutriPro DEFAULT_FOODS (read-only, validated).\n')
    fh.write('// Values are per `per` units (`unit`). Do not edit by hand; user foods live in the db `foods` store.\n')
    fh.write('export const FOODS = Object.freeze([\n')
    for x in foods:
        fh.write('  ' + json.dumps(x, ensure_ascii=False, separators=(',', ':')) + ',\n')
    fh.write(']);\n')
print(len(foods), 'foods,', bad, 'skipped')
